def classify_login(login: str | None) -> str:
    """Map a GitHub login or commit author name to an agent id."""
    name = (login or "").strip().lower()
    if not name:
        return "human"
    if "copilot" in name:
        return "copilot"
    if "codex" in name or name == "chatgpt-connector[bot]":
        return "codex"
    if "claude" in name or "anthropic" in name:
        return "claude"
    if "alice" in name:
        return "alice"
    if name.endswith("[bot]") or name in {"github-actions", "dependabot"}:
        return "ci"
    return "human"


_TEXT_MARKERS = (
    ("claude", re.compile(r"generated (?:with|by) \[claude code\]|claude\.ai/code", re.I)),
    ("codex", re.compile(r"chatgpt\.com/codex|generated (?:with|by) codex", re.I)),
    ("alice", re.compile(r"alice pro github agent|generated by alice", re.I)),
)


def classify_text(text: str | None) -> str | None:
    """Recognise an agent from the footer it leaves in a body, if any."""
    for agent, pattern in _TEXT_MARKERS:
        if pattern.search(text or ""):
            return agent
    return None


def classify_actor(login: str | None, text: str | None = None) -> str:
    """Bots post under their own names; agents using the owner's token sign the text."""
    agent = classify_login(login)
    if agent == "human":
        return classify_text(text) or "human"
    return agent


def classify_branch(ref: str | None) -> str | None:
    prefix = (ref or "").split("/", 1)[0].lower()
    return prefix if prefix in AGENTS else None


_MENTION = re.compile(r"(?<![\w/])@(claude|codex|copilot|alice)\b", re.I)
_EXECUTABLE_MENTION = re.compile(r"(?<![\w/])@(claude-lite|codex|copilot|alice)\b", re.I)
_EXECUTABLE_AGENT = {
    "claude-lite": "claude",
    "codex": "codex",
    "copilot": "copilot",
    "alice": "alice",
}
_MAINTAINER_INTENT = re.compile(r"\bmaintainer\b", re.I)
_EXECUTABLE_AUTHOR_ASSOCIATIONS = {"OWNER", "MEMBER", "COLLABORATOR"}
_CLAUDE_ACTION_RUN = re.compile(r"https://github\.com/[^)\s]+/actions/runs/\d+")


def mentioned_agents(text: str | None) -> list[str]:
    return sorted({match.lower() for match in _MENTION.findall(text or "")})


def executable_mentioned_agents(text: str | None) -> list[str]:
    """Return repository mention tokens that can actually start a configured backend."""
    return sorted(
        {_EXECUTABLE_AGENT[match.lower()] for match in _EXECUTABLE_MENTION.findall(text or "")}
    )



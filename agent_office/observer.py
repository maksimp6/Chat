# Entry point


def run(
    gh: GitHub,
    now: datetime | None = None,
    publish: bool = False,
    limits: Thresholds = DEFAULT_LIMITS,
) -> dict[str, Any]:
    now = now or datetime.now(UTC)
    threads = collect_threads(gh, now, limits)
    findings = [finding for thread in threads for finding in detect_findings(thread, now, limits)]
    digest = render_digest(threads, findings, now, gh.repo, limits)
    result: dict[str, Any] = {
        "generated_at": now.isoformat(),
        "repo": gh.repo,
        "findings": [asdict(finding) for finding in findings],
        "threads": [
            {
                "number": t.number,
                "kind": t.kind,
                "state": t.state,
                "agent": t.owner_agent,
                "title": t.title,
                "base_ref": t.base_ref or None,
                "head_sha": t.head_sha or None,
                "behind_by": t.behind_by,
                "freshness": freshness_state(t) if t.kind == "pr" else None,
                "dispatches": [
                    {"agent": agent, "at": at.isoformat()} for agent, at in t.dispatches
                ],
                "trigger_eligible_dispatches": [
                    {
                        "agent": agent,
                        "at": at.isoformat(),
                        "maintainer_intent": maintainer_intent,
                    }
                    for agent, at, maintainer_intent in t.trigger_eligible_dispatches
                ],
                "executable_dispatches": [
                    {"agent": agent, "at": at.isoformat()} for agent, at in t.executable_dispatches
                ],
                "maintainer_dispatches": [
                    {"agent": agent, "at": at.isoformat()} for agent, at in t.maintainer_dispatches
                ],
                "events": [{**asdict(event), "at": event.at.isoformat()} for event in t.events],
            }
            for t in threads
        ],
        "digest": digest,
    }
    if publish:
        result["tracking_issue"] = publish_digest(gh, digest)
    return result


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--repo", default=os.environ.get("GITHUB_REPOSITORY", "maksimp6/Chat"))
    parser.add_argument("--publish", action="store_true", help="update the tracking issue")
    parser.add_argument("--json-out", help="write threads and findings as JSON to this file")
    parser.add_argument(
        "--fail-on-high",
        action="store_true",
        help="exit 1 when a high-severity finding exists",
    )
    args = parser.parse_args(argv)

    token = os.environ.get("GITHUB_TOKEN") or os.environ.get("GH_TOKEN") or ""
    gh = GitHub(token, args.repo)
    try:
        result = run(gh, publish=args.publish)
    except urllib.error.HTTPError as error:
        print(f"GitHub API error {error.code} for {error.url}", file=sys.stderr)
        return 2

    digest = result["digest"]
    print(digest)
    summary = os.environ.get("GITHUB_STEP_SUMMARY")
    if summary:
        with open(summary, "a", encoding="utf-8") as handle:
            handle.write(digest)
    if args.json_out:
        with open(args.json_out, "w", encoding="utf-8") as handle:
            json.dump(
                {k: v for k, v in result.items() if k != "digest"},
                handle,
                ensure_ascii=False,
                indent=2,
            )
    if result.get("tracking_issue"):
        print(f"Tracking issue: {result['tracking_issue']}", file=sys.stderr)
    high = [f for f in result["findings"] if f["severity"] == "high"]
    return 1 if args.fail_on_high and high else 0


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())

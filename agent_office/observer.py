class GitHub:
    """Minimal GitHub REST client on the standard library."""

    def __init__(self, token: str, repo: str, opener: Callable[..., Any] | None = None):
        self.token = token
        self.repo = repo
        self._open = opener or urllib.request.urlopen

    def request(self, method: str, path: str, payload: Any = None) -> tuple[Any, dict[str, str]]:
        url = path if path.startswith("https://") else f"{API_ROOT}{path}"
        data = json.dumps(payload).encode() if payload is not None else None
        req = urllib.request.Request(url, data=data, method=method)
        req.add_header("Accept", "application/vnd.github+json")
        req.add_header("X-GitHub-Api-Version", "2022-11-28")
        req.add_header("User-Agent", "alice-agent-office-observer")
        if self.token:
            req.add_header("Authorization", f"Bearer {self.token}")
        if data is not None:
            req.add_header("Content-Type", "application/json")
        with self._open(req, timeout=30) as response:
            body = response.read()
            headers = {key.lower(): value for key, value in response.headers.items()}
        return (json.loads(body) if body else None), headers

    def get(self, path: str) -> Any:
        return self.request("GET", path)[0]

    def paginate(self, path: str, key: str | None = None, limit: int = 1000) -> list[Any]:
        items: list[Any] = []
        url: str | None = path
        while url and len(items) < limit:
            page, headers = self.request("GET", url)
            items.extend(page[key] if key else page)
            url = _next_link(headers.get("link", ""))
        return items[:limit]

    def repo_path(self, suffix: str) -> str:
        return f"/repos/{self.repo}{suffix}"


def _next_link(header: str) -> str | None:
    for part in header.split(","):
        section = part.split(";")
        if len(section) > 1 and 'rel="next"' in section[1]:
            return section[0].strip()[1:-1]
    return None


def collect_threads(
    gh: GitHub, now: datetime, limits: Thresholds = DEFAULT_LIMITS, workers: int = 8
) -> list[Thread]:
    """Read open items and those closed recently, then build their threads in parallel."""
    since = (now - limits.recent_window).strftime("%Y-%m-%dT%H:%M:%SZ")
    open_items = gh.paginate(gh.repo_path("/issues?state=open&per_page=100"), limit=300)
    closed_items = gh.paginate(
        gh.repo_path(f"/issues?state=closed&per_page=100&since={urllib.parse.quote(since)}"),
        limit=200,
    )
    items = [
        item
        for item in open_items + closed_items
        if not any(label.get("name") == TRACKING_LABEL for label in item.get("labels") or [])
        and (
            item.get("state") == "open"
            or (parse_time(item.get("closed_at")) or now) >= now - limits.recent_window
        )
    ]

    def load(item: dict[str, Any]) -> Thread:
        number = item["number"]
        timeline = gh.paginate(gh.repo_path(f"/issues/{number}/timeline?per_page=100"), limit=500)
        pull = None
        runs: list[dict[str, Any]] = []
        behind_by: int | None = None
        if "pull_request" in item:
            pull = gh.get(gh.repo_path(f"/pulls/{number}"))
            if item.get("state") == "open":
                sha = pull["head"]["sha"]
                base_ref = pull["base"]["ref"]
                runs = gh.paginate(
                    gh.repo_path(f"/commits/{sha}/check-runs?per_page=100"),
                    key="check_runs",
                    limit=300,
                )
                compare = gh.get(
                    gh.repo_path(
                        f"/compare/{urllib.parse.quote(base_ref, safe='')}...{urllib.parse.quote(sha, safe='')}"
                    )
                )
                behind_by = int(compare["behind_by"])
        return build_thread(item, timeline, pull, runs, behind_by=behind_by)

    with ThreadPoolExecutor(max_workers=workers, thread_name_prefix="observer") as pool:
        return list(pool.map(load, items))


def ensure_tracking_label(gh: GitHub) -> None:
    """Create the tracking label so the next run can find the issue by it."""
    try:
        gh.request(
            "POST",
            gh.repo_path("/labels"),
            {
                "name": TRACKING_LABEL,
                "color": "5319e7",
                "description": "Digest of the agent observer",
            },
        )
    except urllib.error.HTTPError as error:
        if error.code != 422:  # 422: the label already exists
            raise


def publish_digest(gh: GitHub, digest: str) -> str:
    """Rewrite the tracking issue with the digest, creating it on first run."""
    existing = gh.get(gh.repo_path(f"/issues?state=open&labels={TRACKING_LABEL}&per_page=10")) or []
    existing = [issue for issue in existing if "pull_request" not in issue]
    if existing:
        number = existing[0]["number"]
        issue = gh.request("PATCH", gh.repo_path(f"/issues/{number}"), {"body": digest})[0]
    else:
        ensure_tracking_label(gh)
        issue = gh.request(
            "POST",
            gh.repo_path("/issues"),
            {"title": TRACKING_TITLE, "body": digest, "labels": [TRACKING_LABEL]},
        )[0]
    return issue["html_url"]



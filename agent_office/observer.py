def render_digest(
    threads: list[Thread],
    findings: list[Finding],
    now: datetime,
    repo: str,
    limits: Thresholds = DEFAULT_LIMITS,
    events_per_thread: int = 12,
    max_threads: int = 40,
) -> str:
    """Markdown digest for the tracking issue and the workflow summary."""
    open_threads = [thread for thread in threads if thread.state == "open"]
    recent = now - limits.recent_window
    merged = [
        thread
        for thread in threads
        if thread.state == "merged"
        and any(e.action == "смержил" and e.at >= recent for e in thread.events)
    ]

    lines = [
        DIGEST_MARKER,
        "# Наблюдатель: офис агентов",
        "",
        f"Обновлено {now:%Y-%m-%d %H:%M} UTC · репозиторий `{repo}` · "
        f"открыто {sum(t.kind == 'pr' for t in open_threads)} PR и "
        f"{sum(t.kind == 'issue' for t in open_threads)} задач · "
        f"смержено за сутки {len(merged)}.",
        "",
        "| Агент | Открытые PR | Задачи в работе | Шагов за сутки |",
        "| --- | ---: | ---: | ---: |",
    ]
    steps = Counter(e.agent for t in threads for e in t.events if e.at >= recent)
    for agent in AGENTS:
        prs = sum(t.kind == "pr" and t.owner_agent == agent for t in open_threads)
        issues = sum(t.kind == "issue" and t.owner_agent == agent for t in open_threads)
        lines.append(f"| {AGENT_LABELS[agent]} | {prs} | {issues} | {steps[agent]} |")

    lines += ["", "## Требует внимания", ""]
    by_item: dict[int, list[Finding]] = {}
    for item in findings:
        by_item.setdefault(item.number, []).append(item)
    if by_item:
        worst = {n: min(SEVERITY_ORDER[f.severity] for f in group) for n, group in by_item.items()}
        for number in sorted(by_item, key=lambda n: (worst[n], -n)):
            group = sorted(by_item[number], key=lambda f: SEVERITY_ORDER[f.severity])
            head = group[0]
            lines.append(
                f"- {SEVERITY_ICONS[head.severity]} [#{number}]({head.url}) {_escape(head.title)} "
                f"({AGENT_LABELS.get(head.agent, head.agent)}): "
                + "; ".join(_escape(f.message) for f in group)
            )
    else:
        lines.append("Всё идёт по плану, зависших задач нет.")

    flagged = set(by_item)
    shown_threads = [
        t
        for t in threads
        if t.number in flagged or t.last_activity >= recent or t.owner_agent in AGENTS
    ]
    ordered = sorted(
        shown_threads,
        key=lambda t: (t.number not in flagged, t.state != "open", -t.last_activity.timestamp()),
    )[:max_threads]
    hidden = len(threads) - len(ordered)
    lines += ["", "## Треды", ""]
    if hidden:
        lines += [
            f"Не показаны ещё {hidden}: тихие задачи без агента или сверх {max_threads} тредов.",
            "",
        ]
    for thread in ordered:
        icon = {"open": "🟢", "merged": "🟣", "closed": "⚫"}.get(thread.state, "")
        kind = "PR" if thread.kind == "pr" else "Задача"
        draft = " · черновик" if thread.draft else ""
        ci = "" if thread.kind == "issue" else f" · CI: {checks_state(thread)}"
        freshness = "" if thread.kind == "issue" else f" · freshness: {freshness_state(thread)}"
        links = (
            f" · PR {', '.join(f'#{n}' for n in thread.linked_prs)}" if thread.linked_prs else ""
        )
        owner = AGENT_LABELS.get(thread.owner_agent, thread.owner_agent)
        lines.append(
            f"<details><summary>{icon} {kind} #{thread.number} {_escape(thread.title)} · "
            f"{owner}{draft}{ci}{freshness}{links}</summary>"
        )
        lines.append("")
        lines.append(f"[Открыть на GitHub]({thread.url})")
        lines.append("")
        shown = thread.events[-events_per_thread:]
        if len(thread.events) > len(shown):
            lines.append(f"- … ещё {len(thread.events) - len(shown)} шагов раньше")
        for event in shown:
            who = AGENT_LABELS.get(event.agent, event.agent)
            actor = f" ({_escape(event.actor)})" if event.actor and event.agent != "human" else ""
            if event.agent == "human":
                who = _escape(event.actor) or who
            lines.append(f"- {event.at:%m-%d %H:%M} **{who}**{actor}: {_escape(event.action)}")
        lines += ["", "</details>"]

    text = "\n".join(lines) + "\n"
    if len(text) > ISSUE_BODY_LIMIT:
        text = (
            text[: ISSUE_BODY_LIMIT - 60].rsplit("\n", 1)[0] + "\n\n… сводка обрезана по размеру.\n"
        )
    return text


def _escape(text: str) -> str:
    """Keep quoted text inert: no HTML, and no @mentions that would ping or wake agents."""
    return text.replace("<", "&lt;").replace(">", "&gt;").replace("@", "@\u200b")



def parse_time(value: str | None) -> datetime | None:
    if not value:
        return None
    return datetime.fromisoformat(value.replace("Z", "+00:00"))


def _login(obj: dict[str, Any] | None) -> str:
    return (obj or {}).get("login") or ""


def _first_line(text: str | None, limit: int = 90) -> str:
    line = next((part.strip() for part in (text or "").splitlines() if part.strip()), "")
    line = re.sub(r"\s+", " ", line)
    return line if len(line) <= limit else line[: limit - 1] + "…"


def timeline_event(raw: dict[str, Any]) -> Event | None:
    """Turn one GitHub timeline entry into a thread event."""
    kind = raw.get("event") or ""
    if kind == "committed":
        author = (raw.get("author") or {}).get("name") or ""
        at = parse_time((raw.get("author") or {}).get("date"))
        message = raw.get("message") or ""
        return (
            Event(
                at,
                author,
                classify_actor(author, message),
                f"коммит «{_first_line(message)}»",
                raw.get("html_url") or "",
                kind,
            )
            if at
            else None
        )

    at = parse_time(raw.get("created_at") or raw.get("submitted_at"))
    if at is None:
        return None
    actor = _login(raw.get("user")) or _login(raw.get("actor"))
    body = raw.get("body") or ""
    url = raw.get("html_url") or ""

    if kind == "commented":
        action = f"комментарий: {_first_line(body)}" if body else "комментарий"
    elif kind == "reviewed":
        state = (raw.get("state") or "").lower()
        action = {
            "approved": "одобрил PR",
            "changes_requested": "запросил изменения",
        }.get(state, "оставил ревью")
    elif kind == "assigned":
        action = f"назначил {_login(raw.get('assignee'))}"
    elif kind == "unassigned":
        action = f"снял {_login(raw.get('assignee'))}"
    elif kind == "labeled":
        action = f"метка «{(raw.get('label') or {}).get('name', '')}»"
    elif kind == "review_requested":
        reviewer = _login(raw.get("requested_reviewer")) or (
            (raw.get("requested_team") or {}).get("name") or ""
        )
        action = f"запросил ревью у {reviewer}"
    elif kind == "cross-referenced":
        source = (raw.get("source") or {}).get("issue") or {}
        label = "PR" if "pull_request" in source else "issue"
        action = f"упомянут в {label} #{source.get('number')} «{_first_line(source.get('title'))}»"
        url = source.get("html_url") or url
        if not actor:
            # Fall back to the referencing item's author, signed footer included.
            actor = _login(source.get("user"))
            body = source.get("body") or ""
    elif kind in {"merged", "closed", "reopened", "ready_for_review", "convert_to_draft"}:
        action = {
            "merged": "смержил",
            "closed": "закрыл",
            "reopened": "переоткрыл",
            "ready_for_review": "отметил PR готовым",
            "convert_to_draft": "вернул PR в черновик",
        }[kind]
    elif kind in {"head_ref_force_pushed", "head_ref_deleted", "head_ref_restored"}:
        action = kind.replace("_", " ")
    elif kind.startswith("copilot_work"):
        action = "Copilot начал работу" if "started" in kind else "Copilot закончил работу"
        actor = actor or "Copilot"
    else:
        return None
    return Event(at, actor, classify_actor(actor, body), action, url, kind)


def build_thread(
    item: dict[str, Any],
    timeline: list[dict[str, Any]],
    pull: dict[str, Any] | None = None,
    check_runs: list[dict[str, Any]] | None = None,
    behind_by: int | None = None,
) -> Thread:
    """Assemble the thread of one issue or pull request from GitHub data."""
    is_pr = pull is not None or "pull_request" in item
    author = _login(item.get("user"))
    body = item.get("body") or ""
    created_at = parse_time(item.get("created_at")) or datetime.now(UTC)

    if is_pr:
        head = (pull or {}).get("head") or {}
        head_ref = head.get("ref")
        owner_agent = classify_branch(head_ref) or classify_actor(author, body)
        merged = bool(
            (pull or {}).get("merged_at") or (item.get("pull_request") or {}).get("merged_at")
        )
        state = "merged" if merged else item.get("state", "open")
    else:
        owner_agent = "human"
        state = item.get("state", "open")

    thread = Thread(
        number=item["number"],
        title=item.get("title") or "",
        url=item.get("html_url") or "",
        kind="pr" if is_pr else "issue",
        state=state,
        owner_agent=owner_agent,
        created_at=created_at,
        draft=bool((pull or {}).get("draft") or item.get("draft")),
        mergeable_state=(pull or {}).get("mergeable_state") or "",
        base_ref=str(((pull or {}).get("base") or {}).get("ref") or ""),
        head_sha=str(((pull or {}).get("head") or {}).get("sha") or ""),
        behind_by=behind_by,
    )
    thread.events.append(
        Event(
            created_at,
            author,
            classify_actor(author, body),
            "открыл PR" if is_pr else "открыл задачу",
            thread.url,
        )
    )
    if not is_pr:
        _record_dispatch(
            thread,
            body,
            created_at,
            author,
            author_association=item.get("author_association"),
        )
        for assignee in item.get("assignees") or []:
            if classify_login(_login(assignee)) == "copilot":
                thread.dispatches.append(("copilot", created_at))

    for raw in timeline:
        event = timeline_event(raw)
        if event is None:
            continue
        thread.events.append(event)
        kind = raw.get("event")
        if kind == "cross-referenced":
            source = (raw.get("source") or {}).get("issue") or {}
            if "pull_request" in source and source.get("number") not in thread.linked_prs:
                thread.linked_prs.append(source["number"])
        elif kind == "commented":
            if (
                event.agent in AGENTS
                and classify_login(event.actor) == event.agent
                and _is_backend_acknowledgement(event.agent, raw.get("body"), kind)
            ):
                _acknowledge_backend_dispatch(thread, event.agent, event.at)
            _record_dispatch(
                thread,
                raw.get("body"),
                event.at,
                event.actor,
                author_association=raw.get("author_association"),
            )
        elif kind == "reviewed":
            if (
                event.agent in AGENTS
                and classify_login(event.actor) == event.agent
                and _is_backend_acknowledgement(event.agent, raw.get("body"), kind)
            ):
                _acknowledge_backend_dispatch(thread, event.agent, event.at)
        elif not is_pr and kind == "assigned":
            if classify_login(_login(raw.get("assignee"))) == "copilot":
                thread.dispatches.append(("copilot", event.at))
        elif not is_pr and kind == "unassigned":
            if classify_login(_login(raw.get("assignee"))) == "copilot":
                thread.dispatches = [d for d in thread.dispatches if d[0] != "copilot"]
        elif not is_pr and kind == "labeled":
            if (raw.get("label") or {}).get("name") == "alice":
                thread.dispatches.append(("alice", event.at))

    if not is_pr:
        agents = [agent for agent, _ in thread.dispatches]
        thread.owner_agent = agents[-1] if agents else "human"

    for run in check_runs or []:
        name = run.get("name") or "check"
        thread.checks[name] = run.get("conclusion") or run.get("status") or "queued"
        started = parse_time(run.get("started_at") or run.get("created_at"))
        pending = not run.get("conclusion")
        if (
            pending
            and started
            and (thread.checks_started_at is None or started < thread.checks_started_at)
        ):
            thread.checks_started_at = started

    thread.events.sort(key=lambda event: event.at)
    return thread


def _record_dispatch(
    thread: Thread,
    text: str | None,
    at: datetime,
    actor: str,
    *,
    author_association: str | None = None,
) -> None:
    """Record mention intent separately from trigger eligibility and execution evidence."""
    poster = classify_login(actor)
    for agent in mentioned_agents(text):
        if agent != poster:
            thread.dispatches.append((agent, at))

    if (author_association or "").upper() not in _EXECUTABLE_AUTHOR_ASSOCIATIONS:
        return

    maintainer_intent = bool(thread.kind == "pr" and _MAINTAINER_INTENT.search(text or ""))
    for agent in executable_mentioned_agents(text):
        if agent != poster:
            thread.trigger_eligible_dispatches.append((agent, at, maintainer_intent))


def _is_backend_acknowledgement(agent: str, body: str | None, kind: str) -> bool:
    """Require provider-specific evidence that a trigger reached the execution backend."""
    if kind == "reviewed":
        return True
    if agent == "claude":
        return kind == "commented" and bool(_CLAUDE_ACTION_RUN.search(body or ""))
    return kind == "commented"


def _acknowledge_backend_dispatch(thread: Thread, agent: str, at: datetime) -> None:
    """Promote the latest eligible mention only after that backend visibly acknowledges it."""
    already_executed = set(thread.executable_dispatches)
    candidates = [
        candidate
        for candidate in thread.trigger_eligible_dispatches
        if candidate[0] == agent
        and candidate[1] <= at
        and (candidate[0], candidate[1]) not in already_executed
    ]
    if not candidates:
        return

    target, dispatched_at, maintainer_intent = max(candidates, key=lambda item: item[1])
    thread.executable_dispatches.append((target, dispatched_at))
    if target == "claude" and maintainer_intent:
        thread.maintainer_dispatches.append((target, dispatched_at))


